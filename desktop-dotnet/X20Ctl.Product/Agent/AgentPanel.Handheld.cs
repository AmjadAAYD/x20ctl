            Children = { pupil, new Sh.Rectangle { Width = 10, Height = 28, RadiusX = 5, RadiusY = 5, Fill = Brushes.White, Opacity = .6, Effect = new BlurEffect { Radius = 4 } } },
        };
        var eyeball = new Grid

        var pupil = new Sh.Rectangle { Width = 30, Height = 54, RadiusX = 15, RadiusY = 15, Fill = new SolidColorBrush(eyeColor), Effect = new DropShadowEffect { Color = eyeColor, BlurRadius = 30, ShadowDepth = 0, Opacity = 1 } };

    void BuildHandheld(Canvas pad, FrameworkElement screen)
    {
        handheld = pad;
        string model = FinishModel(modelId), key = BodyKey(model);
        var g = Handhelds[model];

        // the body: the controller's own two halves joined by a housing of their own plastic round the screen, made once from
        // the app's art of the colour this pad is (tools/handheld-grips.py, then tools/handheld-body.py), so it reads as one handheld
        var body = new Image
        {
            Source = BodyArt(key), Width = DesignWidth, Height = DesignHeight, Stretch = Stretch.Fill,
            Effect = new DropShadowEffect { BlurRadius = 46, ShadowDepth = 18, Direction = 270, Opacity = .6, Color = Colors.Black }, CacheMode = new BitmapCache(),
        };
        RenderOptions.SetBitmapScalingMode(body, BitmapScalingMode.HighQuality);
        Drag(At(pad, body, 0, 0));
        bool Pale(string k) => Luma(Hx(Finishes[k])) > .62;
        At(pad, screen, ScreenX, ScreenY);

        // light bars down both sides of the screen, in the agent's state colour (they are its player lights)
        double barH = (ScreenH - 120) / 2;
        for (int i = 0; i < 4; i++)
        {
            bool left = i < 2; double y = ScreenY + 50 + (i % 2) * (barH + 20);
            leds[i] = At(pad, new Border { Width = 5, Height = barH, CornerRadius = new(2.5), IsHitTestVisible = false, Effect = new BlurEffect { Radius = 3 } },
                left ? ScreenX - Frame + 6 : ScreenX + ScreenW + Frame - 11, y);
        }
        // the model's name, set into the frame under the screen
        var nameplate = At(pad, new TextBlock
        {
            Text = string.Join(" ", padName.ToUpperInvariant().ToCharArray()), Width = 400, TextAlignment = TextAlignment.Center, FontSize = 11, FontWeight = FontWeights.Bold, IsHitTestVisible = false,
            Foreground = Plate(Pale(key)),
        }, DesignWidth / 2 - 200, ScreenY + ScreenH + 8);
        // the player picks another colour in the Zone: the handheld changes with it
        padColour += who =>
        {
            if (who != player) return;
            string now = BodyKey(model); if (now == key) return;
            key = now; body.Source = BodyArt(key); nameplate.Foreground = Plate(Pale(key));
        };

        // the sticks are its eyes
        LedEye(pad, g.LeftStick, g.Eye, 1); LedEye(pad, g.RightStick, g.Eye, -1);

        // the photo's own controls are buttons. D-pad: scroll the conversation, step through the ideas
        double arm = g.Arm;
        foreach (var (dx, dy, tip, act) in new (double, double, string, Action)[]
        {
            (0, -1, "Scroll up", () => scroller.ScrollToVerticalOffset(scroller.VerticalOffset - 140)),
            (0, 1, "Scroll down", () => scroller.ScrollToVerticalOffset(scroller.VerticalOffset + 140)),
            (-1, 0, "Previous idea", () => Idea(-1)),
            (1, 0, "Next idea", () => Idea(1)),
        })
            pad.Children.Add(Hit(g.Dpad.X + dx * arm - 22, g.Dpad.Y + dy * arm - 22, 44, 44, 10, tip, act));
        // face buttons: A sends, B goes back, X starts over, Y searches the ideas
        double r = g.Button + 4;
        foreach (var (at, tip, act) in new (Point, string, Action)[]
        {
            (g.A, "A · Send", Send),
            (g.B, "B · Back", () => { if (SettingsOpen) ShowSettingsPage(false); else CloseRequested?.Invoke(); }),
            (g.X, "X · New conversation", Restart),
            (g.Y, "Y · Search the ideas", () => { ShowView(View.Ideas); Search.Focus(); Search.SelectAll(); Look(Gaze.Ideas); }),
        })
            pad.Children.Add(Hit(at.X - r, at.Y - r, 2 * r, 2 * r, r, tip, act));
        // the bumpers along each grip's top edge: LB takes back the last change, RB puts the agent away
        pad.Children.Add(Hit(g.LeftX + g.Width * .3, GripTop - 6, g.Width * .42, 44, 18, "LB · Undo the last change", UndoLast));
        pad.Children.Add(Hit(g.RightX + g.RightWidth * .28, GripTop - 6, g.RightWidth * .42, 44, 18, "RB · Put the agent away", LeaveAgent));
        BuildLove(pad);
    }


            Effect = new DropShadowEffect { Color = eyeColor, BlurRadius = 24, ShadowDepth = 0, Opacity = 1 },
        };
        Canvas.SetLeft(squint, 45); Canvas.SetTop(squint, 40); host.Children.Add(squint);
        HeartEye(host, led); SpiralEye(host, led, inward);
        At(pad, host, c.X - 62, c.Y - 62);
        eyes.Add((lookAt, lid, inward)); squints.Add((led, squint));
        ledParts.Add(pupil); ledParts.Add(squint); pupils.Add(pupil); ApplyEyeStyle();
        googlies.Add(new Googly { Jiggle = jiggle, Look = lookAt, Centre = c });
    }

    // ---- the LED eyes: a spring with little damping, pushed by the handheld's own movement, kept inside the eye ----
    bool physicsOn; Point lastBody;
    Point BodyAt => new(offset.X + shake.X, offset.Y + shake.Y);
    void PhysicsStart()
    {
        if (physicsOn || !Motion || googlies.Count == 0) return;
        physicsOn = true; lastBody = BodyAt; CompositionTarget.Rendering += Slosh;
    }
    void PhysicsStop()
    {
        if (!physicsOn) return;
        physicsOn = false; CompositionTarget.Rendering -= Slosh;
    }
    void Slosh(object? sender, EventArgs e)
    {
        var now = BodyAt; var moved = now - lastBody; lastBody = now;
        Point? pointer = handheld != null && gazeNow == Gaze.Idle && !busy && Mouse.LeftButton == MouseButtonState.Released ? Mouse.GetPosition(handheld) : null;
        int index = 0;
        foreach (var g in googlies)
        {
            var target = DizzyPull(index++);
            if (pointer is Point p) { var d = p - g.Centre; if (d.Length > 1) target += d / d.Length * Math.Min(16, d.Length / 25); }
            g.Vel -= moved * .45;
            g.Vel += (target - g.Pos) * .085; g.Vel *= .86; g.Pos += g.Vel;
            var total = new Vector(g.Look.X + g.Pos.X, g.Look.Y + g.Pos.Y);
            const double room = 24;
            if (total.Length > room)
            {
                var n = total / total.Length; g.Pos -= n * (total.Length - room);
                double outward = g.Vel * n; if (outward > 0) g.Vel -= n * outward * 1.6; // it bounces off the rim
            }
            g.Jiggle.X = g.Pos.X; g.Jiggle.Y = g.Pos.Y;
        }
    }

                new Sh.Ellipse { Stroke = new SolidColorBrush(Color.FromArgb(150, 0, 0, 0)), StrokeThickness = 5 },
            },
        };
        host.Children.Add(eyeball);
        // laughing: the LED draws a ">" or "<" instead
        var squint = new Sh.Path
        {
            Data = Geometry.Parse(inward > 0 ? "M 0,0 L 34,22 L 0,44" : "M 34,0 L 0,22 L 34,44"), Width = 34, Height = 44, Stroke = new SolidColorBrush(eyeColor), StrokeThickness = 10,

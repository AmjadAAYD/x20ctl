            Width = 124, Height = 124, Clip = new EllipseGeometry(new Point(62, 62), 62, 62),
            Children =
            {
                new Sh.Ellipse { Fill = new RadialGradientBrush { GradientOrigin = new(.4, .35), GradientStops = { new(Color.FromRgb(35, 38, 45), 0), new(Color.FromRgb(11, 12, 15), 1) } } },

    /// <summary>The model id as the finishes know it: x20_pro, x20, x05_pro, x10, d10, x15, dune.</summary>
    static string FinishModel(string modelId)
    {
        string s = modelId.ToLowerInvariant().Replace('-', '_');
        if (s.StartsWith("x20") && s.Contains("pro")) return "x20_pro";
        if (s.StartsWith("x05")) return "x05_pro";
        foreach (var m in new[] { "x20", "x10", "d10", "x15", "dune" }) if (s.StartsWith(m)) return m;
        return "x20_pro";
    }

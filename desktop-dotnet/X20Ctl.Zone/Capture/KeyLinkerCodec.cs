/// <summary>
/// The KeyLinker configuration frame, read-only: what the official app's CodeHelper calls encrypt and decode, and its
/// CRC. It is obfuscation, not cryptography. This port only decodes frames a recording already holds and builds the
/// two identification questions the official app asks every controller (0x91 and 0xB0); nothing here sends anything.

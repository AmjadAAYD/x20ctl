    public sealed record Frame(byte Opcode, byte Length, byte Serial, byte Nonce, byte[] Payload, byte Crc, bool CrcValid)
    {
        /// <summary>Low five bits of the length field; the top three are a rotating counter.</summary>
        public int DeclaredLength => Length & 0x1F;
    }

    public static byte Crc8(ReadOnlySpan<byte> data)
    {
        byte crc = 0;
        foreach (var b in data) crc = CrcTable[crc ^ b];
        return crc;
    }

    /// <summary>Decodes one frame; null when it is too short or too long to be one.</summary>
    public static Frame? TryDecode(ReadOnlySpan<byte> raw)
    {
        if (raw.Length < 5 || raw.Length > MaxPacket) return null;
        int offset = ((raw[3] ^ SerialKey[3]) & 2) != 0 ? 20 : 0;
        var o = new byte[raw.Length];
        for (int i = 0; i < raw.Length; i++) o[i] = (byte)(raw[i] ^ SerialKey[offset + i]);
        int b3 = ((o[3] ^ 219) - 191) & 0xFF; o[3] = (byte)b3;
        int b2 = ((o[2] ^ b3) + 173) & 0xFF; o[2] = (byte)b2;
        o[1] = (byte)(o[1] ^ ((b2 + b3) + 155));
        o[0] = (byte)(o[0] ^ ((b2 + b3) - 154));
        for (int i = 4; i < raw.Length - 1; i++) o[i] = (byte)(o[i] ^ ((b2 + b3) - SendDataKey[i - 4]));
        var body = o.AsSpan(0, o.Length - 1);
        return new Frame(o[0], o[1], o[2], o[3], o[4..^1], o[^1], Crc8(body) == o[^1]);
    }

    /// <summary>Builds and scrambles one frame (the plain length field, as the query builders use).</summary>
    public static byte[] Build(byte opcode, ReadOnlySpan<byte> payload, byte serial, byte nonce)
    {
        var p = new byte[payload.Length + 5];
        p[0] = opcode; p[1] = (byte)(payload.Length <= 0 ? 5 : payload.Length + 5); p[2] = serial; p[3] = nonce;
        payload.CopyTo(p.AsSpan(4));
        p[^1] = Crc8(p.AsSpan(0, p.Length - 1));
        if (p.Length > MaxPacket) throw new ArgumentException("A frame is at most 20 bytes.");
        byte b2 = p[2], b3 = p[3];
        var o = new byte[p.Length];
        o[0] = (byte)(p[0] ^ ((b2 + b3) - 154));
        o[1] = (byte)(p[1] ^ ((b2 + b3) + 155));
        o[2] = (byte)((b2 - 173) ^ b3);
        o[3] = (byte)((b3 + 191) ^ 219);
        for (int i = 4; i < p.Length - 1; i++) o[i] = (byte)(p[i] ^ ((b2 + b3) - SendDataKey[i - 4]));
        o[^1] = p[^1];
        int offset = (o[3] & 2) * 10;
        for (int i = 0; i < p.Length; i++) o[i] ^= SerialKey[offset + i];
        return o;
    }

    /// <summary>The question "who are you?" (0x91, no payload).</summary>
    public static byte[] IdentityQuery(byte serial, byte nonce) => Build(0x91, [], serial, nonce);

    /// <summary>The descriptor family query: 0xB0 with [position, kind].</summary>
    public static byte[] MenuQuery(byte position, byte kind, byte serial, byte nonce) => Build(0xB0, [position, kind], serial, nonce);
}
